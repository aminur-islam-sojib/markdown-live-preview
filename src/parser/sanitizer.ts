import DOMPurify, { type Config } from 'dompurify';

/**
 * Configuration options for DOMPurify to allow safe Markdown rendering
 * while completely blocking XSS vectors (e.g. script tags, event handlers, javascript: URIs).
 */
export const SANITIZER_CONFIG: Config = {
  USE_PROFILES: {
    html: true,
    svg: true,
    svgFilters: true
  },
  // Disallow potentially hazardous tags even within standard HTML
  FORBID_TAGS: ['script', 'iframe', 'object', 'embed', 'form'],
  // Disallow all inline JavaScript event handlers (onerror, onclick, onload, etc.)
  FORBID_ATTR: ['onerror', 'onload', 'onclick', 'onmouseover', 'onfocus', 'onblur']
};

/**
 * Sanitizes dirty HTML strings using DOMPurify with strict security settings.
 *
 * @param dirtyHtml - The untrusted HTML string generated by markdown parsing or user input.
 * @returns A safe, sanitized HTML string.
 */
export function sanitizeHtml(dirtyHtml: string): string {
  if (!dirtyHtml || typeof dirtyHtml !== 'string') {
    return '';
  }
  return String(DOMPurify.sanitize(dirtyHtml, SANITIZER_CONFIG));
}
